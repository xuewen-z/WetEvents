function Cmap=yellow2purple(WithNaN)

mycolorpoint=[...
%     [137 93 170];...
%     [134 53 148];...
%     [140 131 188];...
    [99 80 112];...
    [184 123 120];...
    [223 74 68];...
    [243 138 33];...
    [249 154 48];...
    [254 199 72];...
    [255 228 140];...
    [255 238 166];...
    [255 248 186];...
    [255 255 227]];
mycolorposition=[1 8 15 22 29 36 43 50 57 64];
mycolormap_r=interp1(mycolorposition,mycolorpoint(:,1),1:64,'linear','extrap');
mycolormap_g=interp1(mycolorposition,mycolorpoint(:,2),1:64,'linear','extrap');
mycolormap_b=interp1(mycolorposition,mycolorpoint(:,3),1:64,'linear','extrap');

colormap=[mycolormap_r',mycolormap_g',mycolormap_b']./255;
colormap=round(colormap*10^4)/10^4;

yellow2purple=flipud(colormap);
    
  Cmap=yellow2purple;

    if nargin<1
      WithNaN=0;
    end
    
    if WithNaN ~= 0
        Cmap=[1,1,1;Cmap];
    end
    
end